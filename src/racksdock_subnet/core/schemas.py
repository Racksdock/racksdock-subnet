"""Pydantic models for every record and protocol message in the system.

Records (registration, qualification, canary, in-rental check) are published inside a
SignedEnvelope whose payload is `record.model_dump()`. The on-chain commitment of a
registration is `hash_obj(record.model_dump())`.
"""
from __future__ import annotations

from enum import StrEnum
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator

from .envelope import utcnow_iso

# --------------------------------------------------------------------------- enums


class InstanceStatus(StrEnum):
    creating = "creating"
    pending_provider = "pending_provider"
    pending = "pending"
    active = "active"
    degraded = "degraded"
    deleting = "deleting"
    deleted = "deleted"
    error = "error"


TERMINAL_STATUSES = {InstanceStatus.deleted, InstanceStatus.error}
BILLABLE_STATUSES = {InstanceStatus.active, InstanceStatus.degraded}


class VmMode(StrEnum):
    verify = "verify"
    tenant = "tenant"


class LaunchType(StrEnum):
    script = "script"
    docker = "docker"


# --------------------------------------------------------------------------- launch configuration


class EnvVar(BaseModel):
    name: str = Field(pattern=r"^[A-Za-z_][A-Za-z0-9_]*$")
    value: str


class PortMapping(BaseModel):
    container_port: int = Field(ge=1, le=65535)
    host_port: int = Field(ge=1, le=65535)


class VolumeMount(BaseModel):
    host_path: str
    container_path: str


class RegistryCredentials(BaseModel):
    username: str | None = None
    password: str | None = None


class DockerConfiguration(BaseModel):
    image: str
    args: str = ""
    envs: list[EnvVar] = Field(default_factory=list)
    port_mappings: list[PortMapping] = Field(default_factory=list)
    volume_mounts: list[VolumeMount] = Field(default_factory=list)
    shared_memory_in_gb: int | None = None
    registry_credentials: RegistryCredentials | None = None


class ScriptConfiguration(BaseModel):
    base64_script: str = Field(max_length=40000)


class LaunchConfiguration(BaseModel):
    type: LaunchType
    docker_configuration: DockerConfiguration | None = None
    script_configuration: ScriptConfiguration | None = None

    @field_validator("docker_configuration", "script_configuration", mode="after")
    @classmethod
    def _noop(cls, v):
        return v

    def model_post_init(self, __context: Any) -> None:
        if self.type == LaunchType.docker and self.docker_configuration is None:
            raise ValueError("docker_configuration required when type is docker")
        if self.type == LaunchType.script and self.script_configuration is None:
            raise ValueError("script_configuration required when type is script")


class UfwRule(BaseModel):
    rule: Literal["allow", "deny", "reject", "limit"]
    port: str | None = None
    proto: Literal["tcp", "udp"] | None = None
    from_ip: str | None = None
    to_ip: str | None = None


class Networking(BaseModel):
    ufw_rules: list[UfwRule] = Field(default_factory=list)


class Threshold(BaseModel):
    date_threshold: str | None = None
    spend_threshold: str | None = None


class UserDataInput(BaseModel):
    """Everything that goes into the VM's cloud-init user-data. Rendered by racksdock_subnet.core.userdata."""

    ssh_public_keys: list[str] = Field(default_factory=list)
    launch_configuration: LaunchConfiguration | None = None
    envs: list[EnvVar] = Field(default_factory=list)
    networking: Networking | None = None
    enable_metrics: bool = False


class CreateInstanceRequest(BaseModel):
    name: str = Field(min_length=1, max_length=50, pattern=r"^[A-Za-z0-9_-]+$")
    node_id: str = "auto"
    instance_type: str | None = Field(default=None, description="for node_id 'auto': profile name or shade_instance_type to pick from")
    deployment: str | None = Field(default=None, description="for node_id 'auto': vm | container")
    region: str | None = None
    os: str | None = None
    ssh_key_ids: list[str] = Field(default_factory=list)
    launch_configuration: LaunchConfiguration | None = None
    envs: list[EnvVar] = Field(default_factory=list, max_length=20)
    tags: list[str] = Field(default_factory=list)
    networking: Networking | None = None
    enable_metrics: bool = False
    alert: Threshold | None = None
    auto_delete: Threshold | None = None
    template_id: str | None = None
    rental_type: Literal["on_demand"] = "on_demand"
    tenant_nonce: str | None = Field(default=None, description="32-byte hex generated by the client; generated server-side if omitted")

    @field_validator("tenant_nonce")
    @classmethod
    def _nonce_hex(cls, v):
        if v is not None:
            if len(v) != 64:
                raise ValueError("tenant_nonce must be 64 hex chars")
            bytes.fromhex(v)
        return v


